def scale2x(g):
    """g: rows of 0/1; twice as wide and high, a pixel's quarters taking a neighbour's where two neighbours agree"""
    h, w = len(g), len(g[0])
    px = lambda x, y: g[y][x] if 0 <= x < w and 0 <= y < h else 0
    o = [[0] * (2 * w) for _ in range(2 * h)]
    for y in range(h):
        for x in range(w):
            p, a, b, c, d = px(x, y), px(x, y - 1), px(x + 1, y), px(x - 1, y), px(x, y + 1)
            o[2 * y][2 * x] = a if c == a and c != d and a != b else p
            o[2 * y][2 * x + 1] = b if a == b and a != c and b != d else p
            o[2 * y + 1][2 * x] = c if d == c and d != b and c != a else p
            o[2 * y + 1][2 * x + 1] = d if b == d and b != a and d != c else p
    return o


SQUARE = "+#*I"                                  # Scale2x makes these worse (a diamond, blobs, bumps): drawn double


def main():
    rows, smooth = [], []
    for code in range(0x20, 0x60):
        g = GLYPHS.get(chr(code), "|".join(["....."] * 6)).split("|")
        assert len(g) == 6 and all(len(r) == 5 for r in g), chr(code)
        name = chr(code) if chr(code) != "\\" else "backslash"
        rows.append("    {" + ", ".join("0x%02X" % sum(1 << (4 - i) for i, c in enumerate(r) if c == "#") for r in g) + "},   /* %s */" % name)
        bits = [[1 if c == "#" else 0 for c in r] for r in g]
        big = [[v for v in r for _ in (0, 1)] for r in bits for _ in (0, 1)] if chr(code) in SQUARE else scale2x(bits)
        smooth.append("    {" + ", ".join("0x%03X" % sum(1 << (9 - i) for i, c in enumerate(r) if c) for r in big) + "},   /* %s */" % name)
    out = ["/* generated by tools/masif_gen_font.py: MASIF's 5 x 6 screen font, the characters 0x20-0x5F; a row is 5 bits,",
           " * the left pixel bit 4 */", "static const uint8_t MASIF_FONT[64][6] = {", *rows, "};",
           "/* the same at 10 x 12 by Scale2x; a row is 10 bits, the left pixel bit 9 */",
           "static const uint16_t MASIF_FONT_SMOOTH[64][12] = {", *smooth, "};", ""]
    Path(__file__).resolve().parents[1].joinpath("firmware", "src", "masif_font.h").write_text("\n".join(out))


if __name__ == "__main__":
    main()
